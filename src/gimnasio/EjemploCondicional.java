package gimnasio;

public class EjemploCondicional {

    public static void main(String[] args) {
        for (int i = 0; i < 10; i++) {


            if (i == 5) {
                System.out.println("Iteración: " + i);
                break; // Sale del bucle cuando i es igual a 5

            }
        }

    }
}


//En este ejemplo, el bucle for se interrumpe cuando i es igual a 5, saliendo del bucle antes de
//completar todas las iteraciones.

